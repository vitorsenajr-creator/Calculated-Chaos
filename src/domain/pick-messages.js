export const PICK_MESSAGES = Object.freeze(LIST.split('\n').map(s => s.trim()).filter(Boolean));

// The saved setting, cleaned: an unknown mode is "off", the text is trimmed
// and cut to PICK_MESSAGE_MAX.
export function normalizePickMessage(raw){
  const mode = PICK_MESSAGE_MODES.includes(raw?.mode) ? raw.mode : 'off';
  const text = String(raw?.text ?? '').replace(/\s+/g, ' ').trim().slice(0, PICK_MESSAGE_MAX);
  return { mode, text };
}

// The message for one checklist: '' for off (or fixed with no text), the typed
// text for fixed, and for random one of the 365 chosen with `random()` (0 to
// 1), never the one at index `last` (the one the previous checklist had).
// Returns { text, index }; index is -1 unless the mode is random.
export function pickMessageFor(raw, { random = Math.random, last = -1 } = {}){
  const { mode, text } = normalizePickMessage(raw);
  if (mode === 'fixed') return { text, index: -1 };
  if (mode !== 'random') return { text: '', index: -1 };
  const n = PICK_MESSAGES.length;
  let index = Math.min(n - 1, Math.floor(random() * n));
  if (index === last) index = (index + 1) % n;
  return { text: PICK_MESSAGES[index], index };
}
